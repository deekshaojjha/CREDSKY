#!/usr/bin/env node
// Reads WEATHER_API_KEY from the environment or a local .env file and writes js/config.js.
// There is no backend, so this key ends up in browser code: restrict it in WeatherAPI's dashboard.

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");

function readDotEnv(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith("#")) continue;
    out[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
  }
  return out;
}

const env = { ...readDotEnv(path.join(root, ".env")), ...process.env };
const key = env.WEATHER_API_KEY || "";

if (!key) {
  console.warn("[build-config] WEATHER_API_KEY not found in environment or .env; the app will show an API configuration error.");
}

const body =
  "// GENERATED by scripts/build-config.cjs from .env. Do not edit or commit.\n" +
  `export const WEATHER_API_KEY = ${JSON.stringify(key)};\n`;

fs.writeFileSync(path.join(root, "js", "config.js"), body);
console.log("[build-config] wrote js/config.js");
